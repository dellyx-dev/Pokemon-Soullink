"""Generates soullink/maps_rs.py: map numbers Ruby/Sapphire to Emerald (same map, same coordinates). The sources
are the disassemblies of both games."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

TARGET = Path(__file__).resolve().parents[1] / "soullink" / "maps_rs.py"


def load(root: Path) -> dict[tuple[int, int], tuple[str, np.ndarray | None]]:
    """Reads maps, names and block data from a disassembly folder."""
    data = root / "data"
    groups = json.loads((data / "maps" / "map_groups.json").read_text(encoding="utf-8"))
    layouts = {lay["id"]: lay for lay in json.loads((data / "layouts" / "layouts.json").read_text(encoding="utf-8"))
               ["layouts"] if lay}
    maps = {}
    for g, group in enumerate(groups["group_order"]):
        for i, name in enumerate(groups[group]):
            map_ = json.loads((data / "maps" / name / "map.json").read_text(encoding="utf-8"))
            lay, blocks = layouts.get(map_["layout"]), None
            if lay and (root / lay["blockdata_filepath"]).exists():
                raw = np.frombuffer((root / lay["blockdata_filepath"]).read_bytes(), "<u2") & 0x3FF
                blocks = raw.reshape(lay["height"], lay["width"])
            maps[(g, i)] = (name, blocks)
    return maps


def best_offset(a: np.ndarray, b: np.ndarray, width: int = 8) -> tuple[float, int, int]:
    """(share of equal blocks, dx, dy) with a[y, x] similar to b[y + dy, x + dx]."""
    best = (0.0, 0, 0)
    for dy in range(-width, width + 1):
        for dx in range(-width, width + 1):
            y0, y1 = max(0, -dy), min(a.shape[0], b.shape[0] - dy)
            x0, x1 = max(0, -dx), min(a.shape[1], b.shape[1] - dx)
            if y1 - y0 < 3 or x1 - x0 < 3:
                continue
            share = float((a[y0:y1, x0:x1] == b[y0 + dy:y1 + dy, x0 + dx:x1 + dx]).mean())
            if share > best[0]:
                best = (share, dx, dy)
    return best


def compare(ruby: Path, emerald: Path) -> dict[tuple[int, int], tuple[int, int, int, int]]:
    """Maps every Ruby/Sapphire map to its Emerald counterpart with the best offset."""
    ru, em = load(ruby), load(emerald)
    after_name = {name: nr for nr, (name, _) in em.items()}
    pairs = {}
    for nr, (name, a) in ru.items():
        if name not in after_name or a is None or em[after_name[name]][1] is None:
            continue
        target, b = after_name[name], em[after_name[name]][1]
        if a.shape == b.shape and float((a == b).mean()) >= 0.5:
            pairs[nr] = (*target, 0, 0)
            continue
        share, dx, dy = best_offset(a, b)
        if share >= 0.75:
            pairs[nr] = (*target, dx, dy)
    return pairs


def write(pairs: dict) -> None:
    """Writes the comparison result as soullink/maps_rs.py."""
    rows = [f"    ({g}, {n}): ({eg}, {en}, {dx}, {dy})," for (g, n), (eg, en, dx, dy) in sorted(pairs.items())]
    TARGET.write_text('"""Ruby/Sapphire -> Emerald: (group, number) -> (group, number, dx, dy). Generated by '
                    'tools/maps_compare.py - do not edit by hand."""\n\nRS_TO_EMERALD = {\n'
                    + "\n".join(rows) + "\n}\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    result = compare(Path(sys.argv[1]), Path(sys.argv[2]))
    write(result)
    print(f"{len(result)} maps: {TARGET}")
